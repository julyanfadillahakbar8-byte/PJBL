<script>
// Navbar scroll
const nav = document.getElementById('navbar');
window.addEventListener('scroll', () => {
  nav.classList.toggle('scrolled', window.scrollY > 30);
});

// Scroll reveal
const reveals = document.querySelectorAll('.reveal');
const obs = new IntersectionObserver(entries => {
  entries.forEach(e => { if (e.isIntersecting) e.target.classList.add('visible'); });
}, { threshold: 0.1 });
reveals.forEach(el => obs.observe(el));

// Region tab filter
function filterRegion(btn, region) {
  document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
  btn.classList.add('active');
  const grid = document.getElementById('daerah-grid');
  grid.style.opacity = '0';
  grid.style.transform = 'translateY(12px)';
  setTimeout(() => {
    grid.style.transition = 'opacity 0.35s ease, transform 0.35s ease';
    grid.style.opacity = '1';
    grid.style.transform = 'translateY(0)';
  }, 180);
}


// Smooth scroll
document.querySelectorAll('a[href^="#"]').forEach(a => {
  a.addEventListener('click', e => {
    const id = a.getAttribute('href').slice(1);
    if (!id) return;
    const t = document.getElementById(id);
    if (t) { e.preventDefault(); t.scrollIntoView({ behavior: 'smooth' }); }
  });
});

// Stats counter animation
const counters = document.querySelectorAll('.stat-item .num');
const targets = [7, 34, 150, 300];
let counted = false;
const countObs = new IntersectionObserver(entries => {
  if (entries[0].isIntersecting && !counted) {
    counted = true;
    counters.forEach((el, i) => {
      const target = targets[i];
      const suffix = el.textContent.includes('+') ? '+' : '';
      let count = 0;
      const step = Math.ceil(target / 40);
      const timer = setInterval(() => {
        count = Math.min(count + step, target);
        el.textContent = count + suffix;
        if (count >= target) clearInterval(timer);
      }, 35);
    });
  }
}, { threshold: 0.5 });
if (counters[0]) countObs.observe(counters[0]);
</script>
